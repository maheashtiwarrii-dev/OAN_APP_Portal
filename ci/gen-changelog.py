#!/usr/bin/env python3
"""Generates db/controller.xml (plan task 0.16a) from db/install.sql, so the Liquibase changelog and the install
script can never drift. One changeset per script, run by SQLcl's own script engine (runOracleScript), so SQLcl
commands, PL/SQL blocks and '/' terminators work exactly as in install.sql.

  * DDL and seed scripts: forward-only (run once; a change needs a new script, as 109/110 do).
  * Packages, views, grants: runOnChange (re-applied when the file changes).
  * Tests (utPLSQL packages): runOnChange.
  * Dev-only scripts (db/dev) are never in the changelog.

usage: python3 ci/gen-changelog.py   then, in SQLcl as OAN_DEPLOY[OAN_DATA]:  cd db  ->  lb update -changelog-file controller.xml
"""
import re
from xml.sax.saxutils import escape

src = open('db/install.sql', encoding='utf-8').read()
files = re.findall(r'^@@(\S+\.sql)\s*$', src, re.M)
assert not any(f.startswith('dev/') for f in files), 'dev scripts must not be in install.sql'

out = ['<?xml version="1.0" encoding="UTF-8"?>',
       '<!-- GENERATED by ci/gen-changelog.py from db/install.sql - do not edit by hand. -->',
       '<databaseChangeLog xmlns="http://www.liquibase.org/xml/ns/dbchangelog"',
       '                   xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"',
       '                   xmlns:n0="http://www.oracle.com/xml/ns/dbchangelog-ext"',
       '                   xsi:schemaLocation="http://www.liquibase.org/xml/ns/dbchangelog',
       '                   http://www.liquibase.org/xml/ns/dbchangelog/dbchangelog-latest.xsd">']
for f in files:
    kind = f.split('/')[0]
    run_on_change = kind in ('packages', 'views', 'grants', 'tests')
    cid = re.sub(r'[^a-z0-9]+', '-', f.lower().replace('.sql', '')).strip('-')
    obj = re.sub(r'[^A-Za-z0-9_]', '_', f.rsplit('/', 1)[-1].replace('.sql', ''))[:120]
    out.append(f'  <changeSet id="{cid}" author="oan" runOnChange="{"true" if run_on_change else "false"}" failOnError="true">')
    out.append(f'    <n0:runOracleScript objectName="{escape(obj)}" ownerName="OAN_DATA" sourceType="FILE">')
    out.append(f'      <n0:source><![CDATA[{f}]]></n0:source>')
    out.append('    </n0:runOracleScript>')
    out.append('  </changeSet>')
out.append('</databaseChangeLog>')
open('db/controller.xml', 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print(f'db/controller.xml: {len(files)} changesets '
      f'({sum(1 for f in files if f.split("/")[0] in ("packages", "views", "grants", "tests"))} runOnChange)')
