#!/usr/bin/env python3
"""Generates db/dev/ut_oan_page_smoke.sql: a DEV-ONLY utPLSQL suite that runs every SQL query of every APEX page
(region sources, LOVs, conditions) on the dev database as each persona - anonymous, member, Platform Admin,
moderator/staff and company contact - with page items bound to a NULL string (as APEX binds them).

It proves at runtime what the offline checks cannot: no query raises (wrong column, conversion error, ORA-00600,
mutating table, a SQL macro inside the WITH clause APEX adds for faceted search - ORA-64630) for any persona. A query that a secure view or package correctly refuses (ORA-20403) counts as
denied, not failed. Needs the synthetic test accounts (610), sample data and 710 (dev staff roles).

usage: python3 ci/gen-page-smoke.py [app dir] [out file]
"""
import glob
import re
import sys

app = sys.argv[1] if len(sys.argv) > 1 else 'oan-app-portal'
out = sys.argv[2] if len(sys.argv) > 2 else 'db/dev/ut_oan_page_smoke.sql'

queries = []
for f in sorted(glob.glob(app + '/pages/*.apx')) + [app + '/shared-components/lovs.apx']:
    s = open(f, encoding='utf-8').read()
    name = re.split(r'[\\/]', f)[-1].replace('.apx', '')
    wraps = re.search(r'type: (facetedSearch|interactiveReport|interactiveGrid|smartFilters)', s) is not None
    for k, m in enumerate(re.finditer(r'```sql\n(.*?)\n\s*```', s, re.S), 1):
        q = '\n'.join(l.strip() for l in m.group(1).split('\n')).strip().rstrip(';')
        q = re.sub(r"(?<!')\:([A-Z][A-Z0-9_]*)\b", 'cast(null as varchar2(4000))', q)        # page and application items -> NULL
        queries.append((f'{name}#{k}', q))
        if wraps and k == 1:
            # APEX wraps faceted-search and interactive-report sources in WITH clauses; SQL macros are not allowed there
            queries.append((f'{name}#{k}-with', f'with base as ({q}) select * from base'))
    for k, m in enumerate(re.finditer(r'\n\s+sqlQuery: ([^\n`]+)\n', s), 1):  # one-line conditions
        q = re.sub(r"(?<!')\:([A-Z][A-Z0-9_]*)\b", 'cast(null as varchar2(4000))', m.group(1).strip().rstrip(';'))
        queries.append((f'{name}#c{k}', q))

for _, q in queries:
    assert '~]' not in q, 'query contains the quote delimiter'

body = []
for i, (label, q) in enumerate(queries, 1):
    body.append(f"    g_q({i}) := q'~{q}~'; g_l({i}) := '{label}';")

PERSONAS = [
    ('anonymous', "oan_ctx_pkg.set_test_viewer(null, 'NONE');"),
    ('member', "oan_ctx_pkg.set_test_viewer(uid('tester.chen'), 'MEMBER');"),
    ('admin', "oan_ctx_pkg.set_test_viewer(uid('tester.bala'), 'MEMBER', 'Y', 'ADMIN:PRIVACY_OFFICER');"),
    ('staff', "oan_ctx_pkg.set_test_viewer(uid('tester.asha'), 'MEMBER', 'N', 'MODERATOR:SUPPORT:CONTENT_EDITOR:EVENT_MANAGER:CHAPTER_ADMIN');"),
    ('company', "oan_ctx_pkg.set_test_viewer(uid('partner.owner'), 'ORG');"),
]

spec = ['create or replace package ut_oan_page_smoke as',
        '  --%suite(Dev page smoke - every page query runs for every persona)',
        '  --%rollback(auto)', '']
for p, _ in PERSONAS:
    spec += [f'  --%test({p}: all {len(queries)} page queries run without error)', f'  procedure {p};']
spec += ['end ut_oan_page_smoke;', '/', '']

impl = ['create or replace package body ut_oan_page_smoke as',
        '  type t_tab is table of varchar2(32767) index by pls_integer;',
        '  g_q t_tab;', '  g_l t_tab;', '',
        '  function uid(p_local in varchar2) return number is',
        '    l_id number;', '  begin',
        "    select id into l_id from oan_users where email = p_local || '@synthetic.oan.invalid';",
        '    return l_id;', '  end uid;', '',
        '  procedure load is', '  begin', '    if g_q.count > 0 then return; end if;'] + body + ['  end load;', '',
        '  procedure run_all(p_persona in varchar2) is',
        '    l_n      number;', '    l_fail   varchar2(32767);', '    l_denied pls_integer := 0;', '  begin',
        '    load;',
        '    for i in 1 .. g_q.count loop',
        '      begin',
        "        execute immediate 'select count(*) from (' || g_q(i) || ')' into l_n;",
        '      exception',
        '        when others then',
        '          if sqlcode = -20403 then',
        '            l_denied := l_denied + 1;',
        '          else',
        "            l_fail := substr(l_fail || chr(10) || g_l(i) || ': ' || substr(sqlerrm, 1, 200), 1, 30000);",
        '          end if;',
        '      end;',
        '    end loop;',
        "    dbms_output.put_line(p_persona || ': ' || g_q.count || ' queries, ' || l_denied || ' correctly denied');",
        "    ut.expect(l_fail, p_persona || ' failures').to_be_null();",
        '  end run_all;', '']
for p, setup in PERSONAS:
    impl += [f'  procedure {p} is', '  begin', f'    {setup}', f"    run_all('{p}');", f'  end {p};', '']
impl += ['end ut_oan_page_smoke;', '/', '']

head = ['-' * 80,
        '-- DEV ONLY utPLSQL, GENERATED by ci/gen-page-smoke.py from the APEXLang export - do not edit by hand.',
        f'-- {len(queries)} page queries x {len(PERSONAS)} personas. Run as OAN_DATA on dev: exec ut.run(\'ut_oan_page_smoke\');',
        '-' * 80]
open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(head + spec + impl))
print(f'{out}: {len(queries)} queries, {len(PERSONAS)} personas')
